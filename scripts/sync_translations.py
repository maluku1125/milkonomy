def s2t(text: str) -> str:
    for s, t in sorted(PHRASE_MAP_S2T.items(), key=lambda x: -len(x[0])):
        text = text.replace(s, t)
    return "".join(CHAR_MAP_S2T.get(c, c) for c in text)


def parse_locale_ts(path: str) -> dict[str, str]:
    src = open(path, encoding="utf-8").read()
    return dict(re.findall(r'"((?:[^"\\]|\\.)*)"\s*:\s*"((?:[^"\\]|\\.)*)"\s*,?', src))


def js_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def write_locale_ts(path: str, mapping: dict[str, str]) -> None:
    items = sorted(mapping.items())
    lines = ["export default {"]
    for i, (k, v) in enumerate(items):
        comma = "," if i < len(items) - 1 else ""
        lines.append(f'  "{js_escape(k)}": "{js_escape(v)}"{comma}')
    lines.append("}")
    output = "\n".join(lines) + "\n"
    open(path, "wb").write(output.encode("utf-8"))


def main() -> int:
    write = "--dry-run" not in sys.argv
    do_all = "--all" in sys.argv

    if not os.path.exists(DATA_JSON):
        print(f"找不到 {DATA_JSON}，請先跑 update_data_local.py")
        return 1

    print("讀取 public/data/data.json…")
    data = json.load(open(DATA_JSON, encoding="utf-8"))
    items = data.get("itemDetailMap", {})
    item_names = sorted(set(v["name"] for v in items.values() if "name" in v))
    print(f"  itemDetailMap: {len(items)} 個 hrid，{len(item_names)} 個 unique name")
    print(f"  gameVersion: {data.get('gameVersion')}")
    print()

    zhcn = parse_locale_ts(ZHCN_TS)
    zhtw = parse_locale_ts(ZHTW_TS)
    en = parse_locale_ts(EN_TS) if do_all else None

    new_in_zhcn = [n for n in item_names if n not in zhcn]
    new_in_zhtw = [n for n in item_names if n not in zhtw]
    print(f"zh-cn 缺漏：{len(new_in_zhcn)}")
    print(f"zh-tw 缺漏：{len(new_in_zhtw)}")
    if do_all and en is not None:
        new_in_en = [n for n in item_names if n not in en]
        print(f"en    缺漏：{len(new_in_en)}（注意：en 鍵以中文 UI 字串為主，英文物品名通常 key=value 不需翻譯）")

    # zh-cn：原則上不自動補（需要英中翻譯，會錯）→ 只列出讓使用者貼回
    if new_in_zhcn:
        print()
        print("⚠ zh-cn 缺漏的物品（需手動翻譯英→中，未自動寫入）：")
        for n in new_in_zhcn[:20]:
            print(f"   - {n}")
        if len(new_in_zhcn) > 20:
            print(f"   …還有 {len(new_in_zhcn) - 20} 個（執行 --all 會印完）")
        if do_all:
            for n in new_in_zhcn[20:]:
                print(f"   - {n}")

    # zh-tw：自動以 zh-cn 已有翻譯做簡轉繁；若 zh-cn 也沒，則跳過
    new_zhtw_added: list[tuple[str, str]] = []
    for n in new_in_zhtw:
        if n in zhcn:
            zhtw[n] = s2t(zhcn[n])
            new_zhtw_added.append((n, zhtw[n]))

    print()
    print(f"zh-tw 自動補上：{len(new_zhtw_added)} 條（其餘 {len(new_in_zhtw) - len(new_zhtw_added)} 條因 zh-cn 也未翻譯而跳過）")
    for n, v in new_zhtw_added[:15]:
        print(f"   {n:50s} → {v}")
    if len(new_zhtw_added) > 15:
        print(f"   …還有 {len(new_zhtw_added) - 15} 條")

    if write and new_zhtw_added:
        write_locale_ts(ZHTW_TS, zhtw)
        print()
        print(f"✓ 已寫入 {ZHTW_TS}")

    if not write:
        print()
        print("（--dry-run 模式，未實際寫檔）")

    return 0


if __name__ == "__main__":
    sys.exit(main())
